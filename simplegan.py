# ============================================================
# Training
# ============================================================

criterion = nn.BCELoss()

g_losses = []
d_losses = []

print("=" * 60)
print("Starting GAN Training")
print("=" * 60)

for epoch in range(1, EPOCHS + 1):

    generator.train()
    discriminator.train()

    total_g_loss = 0.0
    total_d_loss = 0.0

    for batch_index, (real_images, _) in enumerate(dataloader):

        # Move real images to GPU
        real_images = real_images.to(
            device,
            non_blocking=True
        )

        batch_size = real_images.size(0)

        # ----------------------------------------------------
        # Labels
        # ----------------------------------------------------

        real_labels = torch.ones(
            batch_size,
            1,
            device=device
        )

        fake_labels = torch.zeros(
            batch_size,
            1,
            device=device
        )

        # ====================================================
        # Train Discriminator
        # ====================================================

        optimizer_D.zero_grad()

        # ----------------------------------------------------
        # Real images
        # ----------------------------------------------------

        real_output = discriminator(
            real_images
        )

        real_loss = criterion(
            real_output,
            real_labels
        )

        # ----------------------------------------------------
        # Generate fake images
        # ----------------------------------------------------

        noise = torch.randn(
            batch_size,
            NOISE_DIM,
            device=device
        )

        fake_images = generator(noise)

        # ----------------------------------------------------
        # Fake images
        # ----------------------------------------------------

        fake_output = discriminator(
            fake_images.detach()
        )

        fake_loss = criterion(
            fake_output,
            fake_labels
        )

        # ----------------------------------------------------
        # Total discriminator loss
        # ----------------------------------------------------

        d_loss = real_loss + fake_loss

        d_loss.backward()

        optimizer_D.step()

        # ====================================================
        # Train Generator
        # ====================================================

        optimizer_G.zero_grad()

        # Generate new noise
        noise = torch.randn(
            batch_size,
            NOISE_DIM,
            device=device
        )

        fake_images = generator(noise)

        fake_output = discriminator(
            fake_images
        )

        # Generator wants fake images
        # to be classified as REAL

        g_loss = criterion(
            fake_output,
            real_labels
        )

        g_loss.backward()

        optimizer_G.step()

        # ----------------------------------------------------
        # Track losses
        # ----------------------------------------------------

        total_d_loss += d_loss.item()
        total_g_loss += g_loss.item()

    # ========================================================
    # Average losses
    # ========================================================

    avg_d_loss = (
        total_d_loss / len(dataloader)
    )

    avg_g_loss = (
        total_g_loss / len(dataloader)
    )

    d_losses.append(avg_d_loss)
    g_losses.append(avg_g_loss)

    # ========================================================
    # Print progress
    # ========================================================

    print(
        f"Epoch [{epoch:02d}/{EPOCHS}] | "
        f"D Loss: {avg_d_loss:.4f} | "
        f"G Loss: {avg_g_loss:.4f}"
    )

    # ========================================================
    # Generate sample images
    # ========================================================

    generator.eval()

    with torch.no_grad():

        generated_images = generator(
            fixed_noise
        )

    save_image(
        generated_images,
        f"outputs/epoch_{epoch:03d}.png",
        nrow=8,
        normalize=True
    )

    # ========================================================
    # Save checkpoints
    # ========================================================

    torch.save(
        generator.state_dict(),
        "checkpoints/generator_latest.pth"
    )

    torch.save(
        discriminator.state_dict(),
        "checkpoints/discriminator_latest.pth"
    )

